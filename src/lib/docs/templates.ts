export const templateDef = (code: string) => DOC_TEMPLATES.find((t) => t.code === code) ?? null;

/** แทนตัวแปร {{…}} — ตัวแปรที่ไม่มีค่าเปลี่ยนเป็น "…………" ให้เห็นว่าต้องเติม · ตัวแปรที่ไม่รู้จักคงไว้ให้ผู้ใช้เห็น */
export function fillTemplate(text: string, vars: Record<string, string>) {
  return text.replace(/\{\{\s*([^{}]+?)\s*\}\}/g, (m, key: string) => (key in vars ? vars[key] || "…………" : m));
}

/** ตัวแปรที่ยังไม่ถูกแทน (พิมพ์ชื่อผิด/ไม่มีในระบบ) */
export function unknownVariables(text: string) {
  const known = new Set(DOC_VARIABLES.map((v) => v.key));
  return Array.from(new Set(Array.from(text.matchAll(/\{\{\s*([^{}]+?)\s*\}\}/g), (m) => m[1]).filter((k) => !known.has(k))));
}
