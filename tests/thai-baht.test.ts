import { describe, it, expect } from "vitest";
import { bahtText, bahtCols, readNumber } from "@/lib/pay/thai-baht";

describe("จำนวนเงินเป็นตัวอักษร (สเปก 11.5C)", () => {
  it.each([
    [900000, "เก้าพันบาทถ้วน"],
    [150050, "หนึ่งพันห้าร้อยบาทห้าสิบสตางค์"],
    [0, "ศูนย์บาทถ้วน"],
    [100, "หนึ่งบาทถ้วน"],
    [1100, "สิบเอ็ดบาทถ้วน"],
    [2100, "ยี่สิบเอ็ดบาทถ้วน"],
    [1000, "สิบบาทถ้วน"],
    [2000, "ยี่สิบบาทถ้วน"],
    [10100, "หนึ่งร้อยเอ็ดบาทถ้วน"],
    [11100, "หนึ่งร้อยสิบเอ็ดบาทถ้วน"],
    [100100, "หนึ่งพันเอ็ดบาทถ้วน"],
    [25, "ยี่สิบห้าสตางค์"],
    [1, "หนึ่งสตางค์"],
    [11, "สิบเอ็ดสตางค์"],
    [45000, "สี่ร้อยห้าสิบบาทถ้วน"],
    [100000000, "หนึ่งล้านบาทถ้วน"],
    [110000000, "หนึ่งล้านหนึ่งแสนบาทถ้วน"],
    [2100000000, "ยี่สิบเอ็ดล้านบาทถ้วน"],
    [100000100, "หนึ่งล้านเอ็ดบาทถ้วน"],
    [123456789, "หนึ่งล้านสองแสนสามหมื่นสี่พันห้าร้อยหกสิบเจ็ดบาทแปดสิบเก้าสตางค์"],
  ])("%i สตางค์ → %s", (satang, text) => {
    expect(bahtText(satang)).toBe(text);
  });

  it("ล้านซ้อนล้าน และค่าที่ไม่ถูกต้อง", () => {
    expect(readNumber(1_000_000_000_000)).toBe("หนึ่งล้านล้าน");
    expect(() => bahtText(-1)).toThrow();
    expect(() => bahtText(1.5)).toThrow();
  });

  it("แยกช่องบาท | สตางค์", () => {
    expect(bahtCols(90050)).toEqual(["900", "50"]);
    expect(bahtCols(1234500)).toEqual(["12,345", "00"]);
  });
});
